// dist/exo_tokens.rs: GPUI-ready consts for exo-ui-kit's exo-design crate. It is a drop-in for its tokens.rs (the same
// names and types), plus the easing curves, the spring table, and the eight named motions as data.
import { resolve } from './tokens.mjs'

const num = (n) => {
  const s = String(Number(n.toFixed(6)))
  return s.includes('.') || s.includes('e') ? s : `${s}.0`
}
const hex = (c) => `0x${c.hex.slice(1)}`
function colorExpr(c) {
  const [r, g, b] = c.components
  if (c.alpha === 1) return `hex(${hex(c)})`
  if (r === 1 && g === 1 && b === 1) return `ink(${num(c.alpha)})`
  if (r === 0 && g === 0 && b === 0) return `black(${num(c.alpha)})`
  return `Rgba { r: ${num(r)}, g: ${num(g)}, b: ${num(b)}, a: ${num(c.alpha)} }`
}
const prop = (p) => ({ opacity: 'Opacity', scale: 'Scale', scaleX: 'ScaleX', translateX: 'TranslateX', translateXPercent: 'TranslateXPercent', translateY: 'TranslateY', brightness: 'Brightness', flip: 'Flip' })[p]
const curveExpr = (cv) => (cv.type === 'spring' ? 'Curve::Spring' : `Curve::Cubic(${cvName(cv)})`)
// The cubic curves are named consts (EASE_OUT and friends); anything else is written out.
const CURVE_NAMES = new Map()
function cvName(cv) { return CURVE_NAMES.get(JSON.stringify(cv)) ?? `[${cv.value.map(num).join(', ')}]` }
const dur = (ms) => `Duration::from_millis(${ms})`

function channelExpr(c) {
  return `Channel { prop: Prop::${prop(c.prop)}, from: ${num(c.from)}, to: ${num(c.to)}, duration: ${dur(c.duration)}, curve: ${curveExpr(c.curve)}, looping: ${c.loop === true} }`
}
const list = (cs) => `&[${cs.map(channelExpr).join(', ')}]`

export function renderRust(tree) {
  const t = resolve(tree)
  const out = []
  const push = (...xs) => out.push(...xs)

  // The curves first: the named consts the motions and the spring refer to.
  for (const [, tok] of t) {
    if (tok.type === 'cubicBezier' && tok.ext.rust) CURVE_NAMES.set(JSON.stringify(tok.value), tok.ext.rust)
  }

  push(
    '// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit: change the token, then run npm run build.',
    '//! Exo\'s design tokens for GPUI, as exo-ui-kit\'s exo-design crate uses them. A drop-in for its `tokens.rs`: every',
    '//! const there is here with the same name and type. Plus the easing curves, the damped spring, and the eight named',
    '//! motions (`named`), with their reduced-motion variants. The curves and motions are data: `Curve::at` evaluates one.',
    '',
    '#![allow(dead_code)]',
    '',
    'use gpui::Rgba;',
    'use std::time::Duration;',
    '',
    'const fn hex(value: u32) -> Rgba {',
    '    Rgba {',
    '        r: ((value >> 16) & 0xff) as f32 / 255.0,',
    '        g: ((value >> 8) & 0xff) as f32 / 255.0,',
    '        b: (value & 0xff) as f32 / 255.0,',
    '        a: 1.0,',
    '    }',
    '}',
    '',
    'const fn ink(alpha: f32) -> Rgba {',
    '    Rgba { r: 1.0, g: 1.0, b: 1.0, a: alpha }',
    '}',
    '',
    'const fn black(alpha: f32) -> Rgba {',
    '    Rgba { r: 0.0, g: 0.0, b: 0.0, a: alpha }',
    '}',
    '',
  )

  const section = (title) => push('', `// ${title}`)
  const colors = [...t].filter(([, tok]) => tok.type === 'color' && tok.ext.rust)
  section('Colours (Void black, ink at an alpha, text, accent, states)')
  for (const [, tok] of colors) push(`pub const ${tok.ext.rust}: Rgba = ${colorExpr(tok.value)};`)

  section('Glass tones: blur, brightness, contrast, saturation and a tint')
  push(
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct GlassTone {',
    '    pub blur: f32,',
    '    pub brightness: f32,',
    '    pub contrast: f32,',
    '    pub saturation: f32,',
    '    pub tint: Rgba,',
    '}',
  )
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'glass' && x.ext.rust)) {
    const g = tok.value
    push(`pub const ${tok.ext.rust}: GlassTone = GlassTone { blur: ${num(g.blur)}, brightness: ${num(g.brightness)}, contrast: ${num(g.contrast)}, saturation: ${num(g.saturation)}, tint: ${colorExpr(g.tint)} };`)
  }

  section('Shape and layout (px)')
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'dimension' && x.ext.rust)) push(`pub const ${tok.ext.rust}: f32 = ${num(tok.value)};`)
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'number' && x.ext.rust)) {
    const ty = tok.ext.rustType ?? 'f32'
    push(`pub const ${tok.ext.rust}: ${ty} = ${ty === 'f32' ? num(tok.value) : tok.value};`)
  }
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'fontFamily' && x.ext.rust)) push(`pub const ${tok.ext.rust}: &str = "${tok.value[0]}";`)

  section('Durations (Motion: press 90, quick 120, base 160, move 220, flight 300, arrive 280, hold 3000)')
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'duration' && x.ext.rust)) push(`pub const ${tok.ext.rust}: Duration = ${dur(tok.value)};`)

  section('Easing curves: cubic-bezier parameters (x1, y1, x2, y2), solved by `cubic`')
  for (const [, tok] of [...t].filter(([, x]) => x.type === 'cubicBezier' && x.ext.rust)) {
    push(`pub const ${tok.ext.rust}: [f32; 4] = [${tok.value.value.map(num).join(', ')}];`)
  }

  const spring = [...t].find(([, x]) => x.type === 'spring')?.[1]
  if (spring) {
    section('Spring: the linear() table of tokens.css, damped at 0.9 (never overshoots)')
    const sp = spring.value.value
    push(`pub const SPRING_DAMPING: f32 = ${num(sp.damping)};`)
    push(`pub const SPRING_OMEGA: f32 = ${num(sp.omega)};`)
    push(`pub const SPRING_SETTLE: Duration = ${dur(sp.settle)};`)
    push(`/// Peak overshoot of the spring as a fraction of its travel (about 0.63%; the design's limit is 1%).`)
    push(`pub const SPRING_OVERSHOOT: f32 = ${num(sp.overshoot)};`)
    push('/// (t, value) pairs over the motion\'s duration, from rest to the target.')
    push(`pub const SPRING_POINTS: &[(f32, f32)] = &[${spring.value.value.points.map((p) => `(${num(p.t)}, ${num(p.v)})`).join(', ')}];`)
  }

  section('Motion: the curve evaluators (CSS\'s cubic-bezier, and the spring table piecewise)')
  push(
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub enum Curve {',
    '    /// A cubic-bezier with these control points.',
    '    Cubic([f32; 4]),',
    '    /// The damped spring: SPRING_POINTS.',
    '    Spring,',
    '}',
    '',
    'impl Curve {',
    '    /// The eased value at progress `x` in [0, 1]; 0 at 0, 1 at 1, never past 1 for the spring.',
    '    pub fn at(self, x: f32) -> f32 {',
    '        match self {',
    '            Curve::Cubic([x1, y1, x2, y2]) => cubic(x1, y1, x2, y2, x),',
    '            Curve::Spring => spring_at(x),',
    '        }',
    '    }',
    '}',
    '',
    '/// CSS\'s cubic-bezier at `x`, solved by Newton\'s method then bisection.',
    'pub fn cubic(x1: f32, y1: f32, x2: f32, y2: f32, x: f32) -> f32 {',
    '    let curve = |a: f32, b: f32, t: f32| 3.0 * a * t * (1.0 - t).powi(2) + 3.0 * b * t * t * (1.0 - t) + t.powi(3);',
    '    let slope = |a: f32, b: f32, t: f32| 3.0 * a * (1.0 - t).powi(2) + 6.0 * (b - a) * t * (1.0 - t) + 3.0 * (1.0 - b) * t * t;',
    '    let x = x.clamp(0.0, 1.0);',
    '    let mut t = x;',
    '    for _ in 0..8 {',
    '        let d = slope(x1, x2, t);',
    '        if d.abs() < 1e-6 {',
    '            break;',
    '        }',
    '        t -= (curve(x1, x2, t) - x) / d;',
    '    }',
    '    if !(0.0..=1.0).contains(&t) || (curve(x1, x2, t) - x).abs() > 1e-4 {',
    '        let (mut lo, mut hi) = (0.0, 1.0);',
    '        t = x;',
    '        for _ in 0..30 {',
    '            if curve(x1, x2, t) < x { lo = t } else { hi = t }',
    '            t = (lo + hi) / 2.0;',
    '        }',
    '    }',
    '    curve(y1, y2, t)',
    '}',
    '',
    '/// The spring table at progress `x`: linear between its points.',
    'pub fn spring_at(x: f32) -> f32 {',
    '    let x = x.clamp(0.0, 1.0);',
    '    for pair in SPRING_POINTS.windows(2) {',
    '        let ((t0, v0), (t1, v1)) = (pair[0], pair[1]);',
    '        if x <= t1 {',
    '            return v0 + (v1 - v0) * (x - t0) / (t1 - t0);',
    '        }',
    '    }',
    '    1.0',
    '}',
    '',
    '/// The curve sampled at `steps` evenly spaced progress values, from 0 to 1 (for a CSS or GPU table).',
    'pub fn sampled(curve: Curve, steps: usize) -> Vec<f32> {',
    '    (0..steps).map(|i| curve.at(if steps < 2 { 1.0 } else { i as f32 / (steps - 1) as f32 })).collect()',
    '}',
    '',
    '/// A property a channel animates. `Flip` is a FLIP: progress 1 is the inverted box, 0 is at rest.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub enum Prop {',
    '    Opacity,',
    '    Scale,',
    '    ScaleX,',
    '    TranslateX,',
    '    TranslateXPercent,',
    '    TranslateY,',
    '    Brightness,',
    '    Flip,',
    '}',
    '',
    '/// One property moving from `from` to `to` (px, a scale, or progress), over `duration` on `curve`.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Channel {',
    '    pub prop: Prop,',
    '    pub from: f32,',
    '    pub to: f32,',
    '    pub duration: Duration,',
    '    pub curve: Curve,',
    '    /// Runs forever (a sheen, a glide); the consumer pauses it while the window is not focused.',
    '    pub looping: bool,',
    '}',
    '',
    '/// A named motion. `channels` go to the target and `leave` comes back (for a state motion, the trigger is',
    '/// `state`; a press or hover eases into `channels` and out through `leave`). `reduced` is what Reduce motion',
    '/// plays instead: fades and instant changes only, nothing spatial.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Named {',
    '    pub name: &\'static str,',
    '    pub state: bool,',
    '    pub channels: &\'static [Channel],',
    '    pub leave: &\'static [Channel],',
    '    pub scrim: &\'static [Channel],',
    '    pub loops: &\'static [Channel],',
    '    pub reduced: &\'static [Channel],',
    '    pub reduced_leave: &\'static [Channel],',
    '    pub reduced_scrim: &\'static [Channel],',
    '    /// Each item after the first starts this much later (zero for none), up to `stagger_cap` items.',
    '    pub stagger: Duration,',
    '    pub stagger_cap: usize,',
    '    /// Loops pause while the window is not focused.',
    '    pub pause_when_inactive: bool,',
    '}',
    '',
    '/// The delay of item `index` in a staggered list: `stagger` per item, the eighth and later together.',
    'pub fn stagger_delay(named: &Named, index: usize) -> Duration {',
    '    named.stagger * (index.min(named.stagger_cap)) as u32',
    '}',
    '',
  )

  section('The eight named motions every Exo app uses (DESIGN.md › Motion)')
  push('pub mod named {', '    use super::*;', '')
  const motions = [...t].filter(([, x]) => x.type === 'motion')
  const constNames = []
  for (const [path, tok] of motions) {
    const m = tok.value
    const name = path.split('.').pop()
    const constName = name.toUpperCase().replace(/-/g, '_')
    constNames.push(constName)
    push(
      `    /// ${tok.description || name}`,
      `    pub const ${constName}: Named = Named {`,
      `        name: "${name}",`,
      `        state: ${m.kind === 'state'},`,
      `        channels: ${list(m.channels)},`,
      `        leave: ${list(m.leave)},`,
      `        scrim: ${list(m.scrim ?? [])},`,
      `        loops: ${list(m.loops ?? [])},`,
      `        reduced: ${list(m.reduced.channels)},`,
      `        reduced_leave: ${list(m.reduced.leave)},`,
      `        reduced_scrim: ${list(m.reduced.scrim ?? [])},`,
      `        stagger: ${m.stagger !== undefined ? dur(m.stagger) : 'Duration::ZERO'},`,
      `        stagger_cap: ${m.staggerCap ?? 0},`,
      `        pause_when_inactive: ${m.pauseWhenInactive === true},`,
      '    };',
      '',
    )
  }
  push(`    /// Every named motion, in DESIGN.md's order.`, `    pub const ALL: &[&Named] = &[${constNames.map((n) => `&${n}`).join(', ')}];`, '}', '')

  push(
    '#[cfg(test)]',
    'mod tests {',
    '    use super::*;',
    '',
    '    #[test]',
    '    fn curves_land_on_their_ends() {',
    '        for curve in [Curve::Cubic(EASE_OUT), Curve::Cubic(EASE_IN_OUT), Curve::Cubic(EASE_LINEAR), Curve::Spring] {',
    '            assert!(curve.at(0.0).abs() < 1e-3, "{curve:?}");',
    '            assert!((curve.at(1.0) - 1.0).abs() < 1e-6, "{curve:?}");',
    '        }',
    '    }',
    '',
    '    #[test]',
    '    fn spring_overshoots_at_most_one_percent() {',
    '        let samples = sampled(Curve::Spring, 2001);',
    '        let peak = samples.iter().cloned().fold(f32::MIN, f32::max);',
    '        assert!(peak <= 1.01, "overshoot {peak}");',
    '        assert!(peak > 1.0, "a large surface settles with a spring: {peak}");',
    '        assert!((peak - 1.0 - SPRING_OVERSHOOT).abs() < 2e-3, "{peak}");',
    '    }',
    '',
    '    #[test]',
    '    fn small_curves_never_overshoot() {',
    '        for curve in [Curve::Cubic(EASE_OUT), Curve::Cubic(EASE_IN_OUT), Curve::Cubic(EASE_LINEAR)] {',
    '            assert!(sampled(curve, 1001).iter().all(|v| *v >= -1e-6 && *v <= 1.0 + 1e-6), "{curve:?}");',
    '        }',
    '    }',
    '',
    '    #[test]',
    '    fn sampled_spring_starts_at_rest_and_ends_on_target() {',
    '        let s = sampled(Curve::Spring, 10);',
    '        assert_eq!(s.len(), 10);',
    '        assert!(s[0].abs() < 1e-6);',
    '        assert!((s[9] - 1.0).abs() < 1e-6);',
    '    }',
    '',
    '    #[test]',
    '    fn reduced_motion_never_moves_anything() {',
    '        for m in named::ALL {',
    '            for c in m.reduced.iter().chain(m.reduced_leave.iter()).chain(m.reduced_scrim.iter()) {',
    '                if c.duration == Duration::ZERO {',
    '                    continue;',
    '                }',
    '                assert!(!matches!(c.prop, Prop::Scale | Prop::ScaleX | Prop::TranslateX | Prop::TranslateXPercent | Prop::TranslateY | Prop::Flip), "{}", m.name);',
    '                assert!(!c.looping, "{}", m.name);',
    '            }',
    '        }',
    '    }',
    '',
    '    #[test]',
    '    fn a_sheet_settles_by_its_size_not_by_fading_its_glass() {',
    '        assert!(named::SHEET.channels.iter().all(|c| c.prop != Prop::Opacity));',
    '    }',
    '',
    '    #[test]',
    '    fn stagger_is_24ms_and_the_eighth_and_later_are_together() {',
    '        assert_eq!(stagger_delay(&named::LIST_STAGGER, 1), Duration::from_millis(24));',
    '        assert_eq!(stagger_delay(&named::LIST_STAGGER, 7), stagger_delay(&named::LIST_STAGGER, 30));',
    '    }',
    '',
    '    #[test]',
    '    fn there_are_eight_named_motions() {',
    '        assert_eq!(named::ALL.len(), 8);',
    '    }',
    '}',
    '',
  )
  return out.join('\n')
}
